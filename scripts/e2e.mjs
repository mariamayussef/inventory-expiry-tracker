import {chromium} from '@playwright/test';
import {readFileSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
const lines=readFileSync('.local/demo-login.txt','utf8');
const password=lines.match(/Password: (.+)/)[1];
mkdirSync('.local/screenshots',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:8000');
await page.getByLabel('Username',{exact:true}).fill('mariam');await page.getByLabel('Password',{exact:true}).fill(password);
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.getByRole('heading',{name:'Inventory overview',exact:true}).waitFor();
await page.getByText('Rolled oats',{exact:true}).first().waitFor();
await page.screenshot({path:'.local/screenshots/dashboard.png',fullPage:true});
await page.getByRole('button',{name:'Receive stock',exact:true}).click();
await page.getByLabel('Product',{exact:true}).selectOption({label:'Whole milk · STK-1002'});
await page.getByLabel('Quantity (exact units)').fill('12');
await page.getByLabel('Lot code').fill('E2E-'+Date.now());
await page.getByLabel('Expiry date',{exact:true}).fill('2027-12-31');
await page.getByLabel('Reason / review note').fill('Automated browser receipt');
await page.getByRole('button',{name:'Review movement',exact:true}).click();
await page.getByRole('button',{name:'Confirm & post movement',exact:true}).click();
await page.locator('.modal').waitFor({state:'hidden'});
await page.getByRole('status').filter({hasText:'Stock movement posted'}).waitFor();
await page.locator('nav').getByRole('button',{name:'Movements',exact:true}).click();
await page.getByRole('button',{name:'Issue / return / adjust',exact:true}).click();
await page.getByLabel('Product',{exact:true}).selectOption({label:'Whole milk · STK-1002'});
await page.getByLabel('Quantity (exact units)').fill('2');
await page.getByLabel('Reason / review note').fill('Automated browser FEFO issue');
await page.getByRole('button',{name:'Preview FEFO pick',exact:true}).click();
await page.getByRole('heading',{name:'FEFO pick suggestion'}).waitFor();
await page.getByRole('button',{name:'Confirm & post movement',exact:true}).click();
await page.locator('.modal').waitFor({state:'hidden'});
await page.getByRole('status').filter({hasText:'Stock movement posted'}).waitFor();
await page.locator('nav').getByRole('button',{name:'Expiry tracker',exact:true}).click();
await page.getByRole('heading',{name:'Expiry tracker',exact:true}).waitFor();
await page.screenshot({path:'.local/screenshots/before-filter.png',fullPage:true});
await page.getByLabel('Status filter').selectOption('expired');
await page.waitForTimeout(500);
assert(await page.getByText('Expired',{exact:true}).count()>0);
const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export',exact:true}).click();
const download=await downloadPromise;await download.saveAs('.local/e2e-expired.csv');
assert(readFileSync('.local/e2e-expired.csv','utf8').includes('business_timezone'));
await page.screenshot({path:'.local/screenshots/expiry.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(350);
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows viewport');
await page.screenshot({path:'.local/screenshots/mobile.png',fullPage:true});
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: login → receipt → confirmed FEFO issue → expired filter → matching CSV export; desktop/mobile rendering; no browser exceptions.');
await browser.close();
